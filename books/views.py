# ==========================================================
# ADD BOOK COPIES - BULK
# ==========================================================

def book_copy_add(request):

    books = Book.objects.filter(
        status=True
    ).order_by("title")

    if request.method == "POST":

        # --------------------------------------------------
        # COMMON VALUES
        # --------------------------------------------------

        book_id = request.POST.get(
            "book"
        )

        status = request.POST.get(
            "status",
            BookCopy.CopyStatus.AVAILABLE
        )

        shelf = request.POST.get(
            "shelf",
            ""
        ).strip()

        rack = request.POST.get(
            "rack",
            ""
        ).strip()

        purchase_date = request.POST.get(
            "purchase_date"
        ) or None

        purchase_price = request.POST.get(
            "purchase_price"
        ) or None

        condition = request.POST.get(
            "condition",
            "Good"
        )

        notes = request.POST.get(
            "notes",
            ""
        ).strip()

        # --------------------------------------------------
        # QUANTITY
        # --------------------------------------------------

        quantity_value = request.POST.get(
            "quantity",
            "1"
        ).strip()

        try:

            quantity = int(quantity_value)

        except (ValueError, TypeError):

            quantity = 0

        # --------------------------------------------------
        # VALIDATION
        # --------------------------------------------------

        if not book_id:

            messages.error(
                request,
                "Please select a book."
            )

        elif quantity < 1:

            messages.error(
                request,
                "Quantity must be at least 1."
            )

        elif quantity > 1000:

            messages.error(
                request,
                "Maximum 1000 copies can be added at one time."
            )

        else:

            try:

                # --------------------------------------------------
                # ATOMIC TRANSACTION
                # --------------------------------------------------

                with transaction.atomic():

                    book = get_object_or_404(
                        Book,
                        pk=book_id,
                        status=True
                    )

                    # --------------------------------------------------
                    # CREATE COPIES
                    # --------------------------------------------------
                    # Accession Number and Barcode are NOT supplied.
                    #
                    # models.py automatically generates:
                    #
                    # ACC-0001
                    # ACC-0002
                    # ACC-0003
                    #
                    # and:
                    #
                    # LIB000000001
                    # LIB000000002
                    # LIB000000003
                    # --------------------------------------------------

                    for i in range(quantity):

                        copy = BookCopy(

                            book=book,

                            status=status,

                            shelf=shelf,

                            rack=rack,

                            purchase_date=purchase_date,

                            purchase_price=purchase_price,

                            condition=condition,

                            notes=notes,
                        )

                        # Model generates Accession + Barcode
                        copy.save()

                messages.success(
                    request,
                    f"{quantity} book copy/copies added successfully."
                )

                return redirect(
                    "book_copy_list"
                )

            except Exception as e:

                messages.error(
                    request,
                    f"Book copies could not be added: {e}"
                )

    return render(
        request,
        "books/book_copy_form.html",
        {
            "books": books,

            "status_choices": (
                BookCopy.CopyStatus.choices
            ),
        }
    )


