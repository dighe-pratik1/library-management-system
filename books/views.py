# ==========================================================
# HELPER FUNCTION
# ==========================================================

def get_boolean_status(value):
    """
    HTML form मधून आलेला status Boolean मध्ये convert करतो.

    ACTIVE / TRUE / 1 / ON / YES -> True
    बाकी -> False
    """

    if value is None:
        return False

    value = str(value).strip().upper()

    return value in [
        "ACTIVE",
        "TRUE",
        "1",
        "ON",
        "YES"
    ]


